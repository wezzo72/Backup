async function submitToWayback(url) {
  const saveUrl = `https://web.archive.org/save/${url}`;
  const res = await fetch(saveUrl, {
    method: 'GET',
    redirect: 'follow',
    headers: {
      'User-Agent': 'barrandodger-archiver/1.0 (https://barrandodger.com)',
    },
    signal: AbortSignal.timeout(30000),
  });
  const location = res.headers.get('content-location') || res.headers.get('location') || '';
  return { status: res.status, archived: location || `https://web.archive.org/web/*/${url}` };
}

